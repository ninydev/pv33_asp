/*
  Назва: sse.js
  Призначення: Підключення до серверних подій (Server‑Sent Events, SSE) з фронтенду та
  обробка повідомлень у режимі реального часу.

  Що таке SSE:
  - Односпрямований канал: сервер "штовхає" події до клієнта через довготривалий HTTP‑запит.
  - На відміну від WebSocket, зв'язок лише у напрямку сервер→клієнт, проте простіший.
  - Браузер автоматично перепідключається при розриві з'єднання.

  Як це працює у цьому файлі:
  1) Створюємо EventSource з URL '/sse/notifications/subscribe' — це endpoint, який має
     повертати відповідь типу text/event-stream і періодично надсилати події.
  2) Підписуємося на події:
     - onopen: викликається, коли з'єднання встановлено.
     - onmessage: викликається на кожне повідомлення від сервера (event.data).
     - onerror: викликається при помилці або розриві; браузер спробує перепідключитися.
  3) За замовчуванням reconnection delay контролюється самим браузером (зазвичай 2–3 с),
     але сервер може надсилати retry: <ms> у стрімі, щоб змінити інтервал.

  Типові вимоги до бекенду:
  - Відповідь з заголовками: Content-Type: text/event-stream, Cache-Control: no-cache
  - Кожна подія має формат:
        data: <JSON або текст>\n\n
    Можна також вказати event: <назва> і id: <ідентифікатор>.

  Корисні поради:
  - Якщо потрібно припинити отримувати події: eventSource.close();
  - Слідкуйте за витоками пам'яті: закривайте з'єднання при навігації зі сторінки.
  - Для авторизації інколи потрібні куки/токени; EventSource надсилає куки автоматично у межах
    того ж домену. Для CORS — endpoint має дозволяти креденшали, якщо це необхідно.
*/

// 1) Ініціюємо постійне з'єднання з SSE‑endpoint на бекенді.
//const eventSource = new EventSource('/sse/notifications/subscribe'); // URL до контролера, що стрімить події
const eventSource = new EventSource('/sse/connect'); // URL до контролера, що стрімить події

// Спрацьовує, коли канал успішно відкрився.
eventSource.onopen = (event) => {
    console.log('Connected to server'); // Для відладки: підтвердження, що з'єднання встановлено
}

// Отримання кожного повідомлення від сервера.
// event.data — це рядок; за потреби парсимо: const payload = JSON.parse(event.data);
eventSource.onmessage = (event) => {
    console.log("SSE Message", event.data); // Тут можна оновлювати UI, показувати нотифікації тощо
};

// Спрацьовує при помилці/розриві з'єднання.
// Типові сценарії: тайм‑аут, рестарт серверу, втрата мережі.
// Браузер спробує перепідключитися автоматично; можна додати власну логіку повтору або індикатор статусу.
eventSource.onerror = (error) => {
    console.error(error); // Для відладки; у продакшені — показати дружнє повідомлення користувачу
};

